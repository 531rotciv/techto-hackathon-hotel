def send_verification_email(html_body, recipient_email):
    """Sends the summary email to the provided address."""
    if not EMAIL_USER or not EMAIL_PASS:
        print("❌ Error: Sender credentials missing in .env file.")
        return False

    msg = MIMEMultipart("alternative")
    # Updated subject line to exactly match the required format
    msg["Subject"] = "Team # 14 - Hotel Reservation Confirmed!"
    msg["From"] = EMAIL_USER
    msg["To"] = recipient_email

    part = MIMEText(html_body, "html")
    msg.attach(part)

    try:
        print(f"Connecting to SMTP server to send email to {recipient_email}...")
        server = smtplib.SMTP(SMTP_SERVER, SMTP_PORT)
        server.starttls()
        server.login(EMAIL_USER, EMAIL_PASS)
        server.sendmail(EMAIL_USER, recipient_email, msg.as_string())
        server.quit()
        
        print(f"✅ Success: Verification email sent to {recipient_email}!")
        return True
    
    except Exception as e:
        print(f"❌ Failed to send email: {e}")
        return False

